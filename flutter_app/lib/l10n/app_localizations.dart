  // ── General String Lookup ──────────────────────────────────────────────────
  String get(String key) {
    final lang = locale.languageCode;
    return _localizedValues[lang]?[key] ??
        _localizedValues['en']?[key] ??
        key;
  }

  // ── Main Category Resolution ───────────────────────────────────────────────
  String category(String codeOrName) {
    final lang = locale.languageCode;
    final trimmed = codeOrName.trim();

    // 1. Exact match on code (e.g. OPEX-GROCERY)
    if (_categoryCodes.containsKey(trimmed)) {
      final map = _categoryCodes[trimmed]!;
      return map[lang] ?? map['en'] ?? trimmed;
    }

    // 2. Lookup by English or Arabic name
    for (final entry in _categoryCodes.values) {
      if (entry['en']?.toLowerCase() == trimmed.toLowerCase() ||
          entry['ar'] == trimmed ||
          entry['ur'] == trimmed) {
        return entry[lang] ?? entry['en'] ?? trimmed;
      }
    }

    // 3. Fallback: strip prefix if code-like
    if (trimmed.startsWith('OPEX-') || trimmed.startsWith('CAPEX-')) {
      final simple = trimmed.replaceFirst(RegExp(r'^[A-Z]+-'), '');
      return simple;
    }

    return trimmed;
  }

  // ── Sub-Category Resolution (Strict Single Language) ───────────────────────
  String subCategory(String subCodeOrName, {String? nameAr, String? nameEn}) {
    final lang = locale.languageCode;
    final cleanCode = subCodeOrName.trim();

    // 1. If explicit Arabic name provided from database and active language is Arabic:
    if (lang == 'ar') {
      if (nameAr != null && nameAr.trim().isNotEmpty) {
        return nameAr.trim();
      }
      final map = _subCategoryValues[cleanCode];
      if (map != null && map['ar'] != null) {
        return map['ar']!;
      }
      // Check if subCodeOrName is an English key in the dictionary
      for (final entry in _subCategoryValues.values) {
        if (entry['en']?.toLowerCase() == cleanCode.toLowerCase()) {
          return entry['ar'] ?? entry['en']!;
        }
      }
      return nameEn?.trim().isNotEmpty == true ? nameEn!.trim() : cleanCode;
    }

    // 2. If active language is Urdu:
    if (lang == 'ur') {
      final map = _subCategoryValues[cleanCode];
      if (map != null && map['ur'] != null) {
        return map['ur']!;
      }
      for (final entry in _subCategoryValues.values) {
        if (entry['en']?.toLowerCase() == cleanCode.toLowerCase()) {
          return entry['ur'] ?? entry['ar'] ?? entry['en']!;
        }
      }
      if (nameAr != null && nameAr.trim().isNotEmpty) {
        return nameAr.trim();
      }
      return nameEn?.trim().isNotEmpty == true ? nameEn!.trim() : cleanCode;
    }

    // 3. Default: English
    if (nameEn != null && nameEn.trim().isNotEmpty) {
      return nameEn.trim();
    }
    final map = _subCategoryValues[cleanCode];
    if (map != null && map['en'] != null) {
      return map['en']!;
    }
    for (final entry in _subCategoryValues.values) {
      if (entry['ar'] == cleanCode || entry['ur'] == cleanCode) {
        return entry['en'] ?? cleanCode;
      }
    }
    return cleanCode;
  }
}

extension LocalizationExtension on BuildContext {
  String tr(String key) => AppLocalizations.of(this).get(key);
  String trCat(String codeOrName) => AppLocalizations.of(this).category(codeOrName);
  String trSub(String subCodeOrName, {String? nameAr, String? nameEn}) =>
      AppLocalizations.of(this).subCategory(subCodeOrName, nameAr: nameAr, nameEn: nameEn);
  bool get isArabic => Localizations.localeOf(this).languageCode == 'ar';
  bool get isUrdu => Localizations.localeOf(this).languageCode == 'ur';
  bool get isRtl => isArabic || isUrdu;
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      ['en', 'ar', 'ur'].contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(locale);

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}
